"""Composable GSUB stages: binary integer circuit followed by bitwise NOT.

The first circuit is generated by compiler.build; the second stage is appended
as a genuine GSUB substitution (not host-side postprocessing).
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from .compiler import build, encode

SUPPORTED_FIRST = ('add', 'sub', 'and', 'or', 'xor')

def build_not_pipeline(path, operation='add', width=32, not_stages=1):
    if operation not in SUPPORTED_FIRST or width not in (32, 64):
        raise ValueError('unsupported pipeline')
    if not isinstance(not_stages,int) or not isinstance(not_stages,bool) and not_stages < 0: raise ValueError('invalid stage count')
    path=Path(path)
    build(path, operation, width, invert_output=not_stages)
    return path

def decode_not(tokens,width,not_stages=1):
    prefix=('s' if not_stages==0 else 't' if not_stages==1 else f'v{not_stages}_')
    if len(tokens)!=width+1 or any(t not in (prefix+'0',prefix+'1') for t in tokens[:width]):
        raise ValueError('invalid pipeline output')
    return sum((token==prefix+'1')<<i for i,token in enumerate(tokens[:width]))
